import { describe, expect, it } from 'vitest';
import { toWarekiDate, withWareki } from '../src/lib/wareki.js';

describe('toWarekiDate', () => {
  it.each([
    ['2026-06-24', '令和8年6月24日'],
    ['1947-04-07', '昭和22年4月7日'],
    // 改元日の前後（元号は年でなく日で切り替わる）
    ['2019-04-30', '平成31年4月30日'],
    ['2019-05-01', '令和元年5月1日'],
    ['1989-01-07', '昭和64年1月7日'],
    ['1989-01-08', '平成元年1月8日'],
    ['1926-12-24', '大正15年12月24日'],
    ['1926-12-25', '昭和元年12月25日'],
    ['1912-07-29', '明治45年7月29日'],
    ['1912-07-30', '大正元年7月30日'],
    ['1896-04-27', '明治29年4月27日'],
    ['1873-01-01', '明治6年1月1日'],
  ])('%s → %s', (iso, expected) => {
    expect(toWarekiDate(iso)).toBe(expected);
  });

  it.each([
    ['1872-12-31'], // 太陽暦の採用前（旧暦の日付とずれる）
    ['2026-02-30'],
    ['2026-13-01'],
    ['2026/06/24'],
    ['令和8年6月24日'],
    [''],
  ])('解釈できない・範囲外は undefined: %s', (iso) => {
    expect(toWarekiDate(iso)).toBeUndefined();
  });
});

describe('withWareki', () => {
  it('ISO の日付のあとに和暦を括弧で添える', () => {
    expect(withWareki('2026-06-24')).toBe('2026-06-24（令和8年6月24日）');
  });

  it('和暦にできなければ元の文字列のまま', () => {
    expect(withWareki('不明')).toBe('不明');
  });
});
